def generate_service_worker(project: Dict) -> str:
    """Generate service worker"""
    name = project.get("name", "Atmosphere")
    assets = project.get("assets", [])
    
    return f"""// {name} Service Worker
const CACHE_NAME = 'atmosphere-v1';
const PRECACHE_ASSETS = [
  '/',
  '/index.html',
  '/manifest.json',
  '/static/js/main.js',
  '/static/css/main.css',
  {json.dumps(assets)}
].flat();

self.addEventListener('install', (event) => {{
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_ASSETS))
  );
  self.skipWaiting();
}});

self.addEventListener('fetch', (event) => {{
  event.respondWith(
    caches.match(event.request)
      .then((response) => response || fetch(event.request))
      .catch(() => caches.match('/index.html'))
  );
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil(
    caches.keys().then((cacheNames) => {{
      return Promise.all(
        cacheNames
          .filter((name) => name !== CACHE_NAME)
          .map((name) => caches.delete(name))
      );
    }})
  );
}});
"""


def create_pwa_bundle(project: Dict, output_path: Path, assets_dir: Path) -> Path:
    """Create complete PWA bundle as zip"""
    project_name = project.get("name", "atmosphere-pwa").lower().replace(" ", "-")
    zip_path = output_path / f"{project_name}-bundle.zip"
    
    # Generate dynamic files
    app_js = generate_app_js(project, project)
    app_css = generate_app_css(project)
    config_js = generate_config_js(project)
    service_worker = generate_service_worker(project)
    
    manifest = project.get("pwa_manifest", {})
    manifest_json = json.dumps({
        "name": manifest.get("name", "Atmosphere"),
        "short_name": manifest.get("short_name", "Atmosphere"),
        "description": manifest.get("description", "A digital place"),
        "start_url": "/",
        "display": manifest.get("display", "standalone"),
        "orientation": manifest.get("orientation", "any"),
        "theme_color": manifest.get("theme_color", "#050505"),
        "background_color": manifest.get("background_color", "#050505"),
        "icons": [
            {"src": "/icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "/icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}
        ]
    }, indent=2)
    
    # Create zip
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zipf:
        # Add template files
        for file_path, template in PWA_TEMPLATE.items():
            content = template
            content = content.replace("{{name}}", project.get("name", "Atmosphere"))
            content = content.replace("{{description}}", project.get("description", "A digital place"))
            content = content.replace("{{theme_color}}", manifest.get("theme_color", "#050505"))
            content = content.replace("{{manifest}}", manifest_json)
            content = content.replace("{{app_js}}", app_js)
            content = content.replace("{{app_css}}", app_css)
            content = content.replace("{{config_js}}", config_js)
            content = content.replace("{{service_worker}}", service_worker)
            
            zipf.writestr(f"{project_name}/{file_path}", content)
        
        # Add project assets
        if assets_dir.exists():
            for asset_file in assets_dir.glob("*"):
                if asset_file.is_file() and not asset_file.name.endswith("_thumb.jpg"):
                    arcname = f"{project_name}/public/assets/{asset_file.name}"
                    zipf.write(asset_file, arcname)
        
        # Create icons directory placeholder
        zipf.writestr(f"{project_name}/public/icons/.gitkeep", "")
    
    return zip_path
