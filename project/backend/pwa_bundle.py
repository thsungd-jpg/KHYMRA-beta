def generate_app_js(project: Dict, config: Dict) -> str:
    """Generate main App.js with state machine"""
    states = config.get("states", [])
    continuity = config.get("continuity", {})
    cognitive_zero = config.get("cognitiveZero", {})
    
    return f"""import React, {{ useState, useEffect, useRef }} from 'react';
import './App.css';
import config from './config';

function App() {{
  const [currentState, setCurrentState] = useState(null);
  const [backgroundIndex, setBackgroundIndex] = useState(0);
  const [audioPlaying, setAudioPlaying] = useState(false);
  const [volume, setVolume] = useState(0.7);
  const audioRef = useRef(null);
  const transitionInterval = useRef(null);

  // Initialize from config
  useEffect(() => {{
    if (config.states.length > 0) {{
      // Load saved state if continuity enabled
      if (config.continuity.remember_last_state) {{
        const saved = localStorage.getItem('atmosphere_state');
        if (saved) {{
          try {{
            const parsed = JSON.parse(saved);
            setCurrentState(parsed.stateId);
            setBackgroundIndex(parsed.backgroundIndex || 0);
            setVolume(parsed.volume || 0.7);
          }} catch (e) {{
            setCurrentState(config.states[0].id);
          }}
        }} else {{
          setCurrentState(config.states[0].id);
        }}
      }} else {{
        setCurrentState(config.states[0].id);
      }}
    }}
  }}, []);

  // Save state on changes
  useEffect(() => {{
    if (currentState && config.continuity.remember_last_state) {{
      localStorage.setItem('atmosphere_state', JSON.stringify({{
        stateId: currentState,
        backgroundIndex,
        volume,
        timestamp: Date.now()
      }}));
    }}
  }}, [currentState, backgroundIndex, volume]);

  // Background rotation
  useEffect(() => {{
    const state = config.states.find(s => s.id === currentState);
    if (state && state.visual.background_stack.length > 1) {{
      const intervalMs = (state.tempo.transition_pacing_seconds || 14) * 1000;
      
      transitionInterval.current = setInterval(() => {{
        setBackgroundIndex(prev => 
          (prev + 1) % state.visual.background_stack.length
        );
      }}, intervalMs);

      return () => clearInterval(transitionInterval.current);
    }}
  }}, [currentState]);

  const state = config.states.find(s => s.id === currentState);
  if (!state) return <div className="loading">Loading atmosphere...</div>;

  const currentBg = state.visual.background_stack[backgroundIndex];
  const nextBg = state.visual.background_stack[(backgroundIndex + 1) % state.visual.background_stack.length];

  return (
    <div className="atmosphere">
      <div 
        className="background-layer current"
        style={{{{
          backgroundImage: currentBg ? `url(${{currentBg}})` : 'none',
          opacity: 1,
          mixBlendMode: state.visual.blend_modes[0] || 'normal'
        }}}}
      />
      <div 
        className="background-layer next"
        style={{{{
          backgroundImage: nextBg ? `url(${{nextBg}})` : 'none',
          opacity: 0,
          mixBlendMode: state.visual.blend_modes[1] || 'normal'
        }}}}
      />
      
      <div className="info-overlay">
        <h1>{{name}}</h1>
        <p className="state-name">{{state.name}}</p>
        <div className="controls">
          <button onClick={{() => setAudioPlaying(!audioPlaying)}}>
            {{audioPlaying ? 'Pause' : 'Play'}}
          </button>
          <input 
            type="range" 
            min="0" 
            max="1" 
            step="0.01" 
            value={{volume}}
            onChange={{(e) => setVolume(parseFloat(e.target.value))}}
          />
        </div>
      </div>

      {{state.audio.playlist.length > 0 && (
        <audio 
          ref={{audioRef}}
          src={{state.audio.playlist[0]}}
          loop
          autoPlay={{audioPlaying}}
          volume={{volume}}
        />
      )}}
    </div>
  );
}}

export default App;
"""


